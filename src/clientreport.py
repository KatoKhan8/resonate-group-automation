# The thresholds an observation is allowed to be made against. Written down
# rather than chosen in the prose, so "we said their reply rate was low"
# always means the same thing, and so changing the bar is one visible edit.
THRESHOLDS = {
    "held_share_high": 0.25,
    "linkedin_only_share_high": 0.35,
    "small_sample": 30,
}


def observations(data):
    """Deterministic notes on the numbers. No model writes these.

    Each one is a comparison against `THRESHOLDS` with the figures attached.
    An observation a client can check against the table above it is worth
    printing; a generated sentence about "strong momentum in the DACH region"
    is worth less than nothing, because somebody will act on it.
    """
    out = []
    funnel = data.get("funnel") or {}
    contacts = data.get("contacts_found") or 0
    selected = data.get("contacts_selected") or 0
    reachable = data.get("contacts_email_reachable")
    if reachable is None:                       # older stored data
        reachable = data.get("contacts_verified") or 0
    replies = data.get("replies") or 0
    positive = data.get("positive_replies") or 0
    pushed = data.get("emails_pushed") or 0
    linkedin_only = data.get("contacts_linkedin_only") or 0
    # Contacts that *have* an address and cannot be written to. The
    # subtraction used to start from every contact found, which put every
    # contact with no address at all and every LinkedIn-only person into a
    # number explained as verification failure, disagreement or email
    # security - three reasons that describe none of them.
    with_address = (data.get("confirmation") or {}).get(
        "contacts_with_an_address")
    held = max(0, (with_address if with_address is not None
                   else data.get("contacts_found") or 0) - reachable)

    if not pushed:
        out.append(("info",
                    "No outreach has been confirmed sent in this period, so "
                    "no reply rate can be reported. Every figure below "
                    "describes the audience that was built, not its "
                    "performance."))
    if contacts and held / float(contacts) > THRESHOLDS["held_share_high"]:
        out.append(("warn",
                    f"{held:,} of {contacts:,} contacts "
                    f"({100.0 * held / contacts:.0f}%) have an address that "
                    f"cannot be used rather than being "
                    f"contactable by email. That means the address failed "
                    f"verification, the two verifiers disagreed, or email "
                    f"security ruled the domain out - none of them is a "
                    f"delivery failure, and none was guessed past."))
    if contacts and linkedin_only / float(contacts) > \
            THRESHOLDS["linkedin_only_share_high"]:
        out.append(("info",
                    f"{linkedin_only:,} contacts are reachable on LinkedIn "
                    f"only. LinkedIn capacity, not list size, is the limit on "
                    f"this segment."))
    if pushed and replies:
        out.append(("info",
                    f"Reply rate {_rate(replies, pushed)} against confirmed "
                    f"sends."))
    if replies and positive:
        out.append(("good",
                    f"Positive replies {_rate(positive, replies)} of all "
                    f"replies."))
    if 0 < pushed < THRESHOLDS["small_sample"]:
        out.append(("warn",
                    f"Only {pushed:,} confirmed sends in this period. That is "
                    f"below the {THRESHOLDS['small_sample']} this report "
                    f"treats as a readable sample, so no rate here should be "
                    f"used to compare segments."))
    if funnel.get("qualified") is not None and data.get("domains_uploaded"):
        out.append(("info",
                    f"ICP qualification kept "
                    f"{_rate(data.get('domains_qualified'), data.get('domains_uploaded'))} "
                    f"of uploaded domains."))
    if not out:
        out.append(("info",
                    "Nothing in this period crosses a threshold this report "
                    "comments on."))
    return out


