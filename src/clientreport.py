def sections_for(template):
    """Which sections this template may contain, in order."""
    return [key for key, _, templates, _ in SECTIONS if template in templates]


def default_sections(template):
    """What is on unless somebody turns it off.

    Everything the template offers. A default that hides a section is a
    default that quietly changes what a client is told, and the place to make
    that decision is the workspace's report settings, visibly.
    """
    return list(sections_for(template))


def resolve_sections(template, requested=None):
    """The sections that will actually render.

    A key the template does not offer is dropped rather than honoured. That is
    the guard that stops `sections=providers` on an executive report from
    putting the verification waterfall in front of a client - the template
    decides what exists, and the request only narrows it.
    """
    allowed = sections_for(template)
    # An empty request means the template's defaults, not an empty document.
    # A form submits nothing at all for a checkbox group where every box is
    # cleared, and honouring that literally produced a one-page PDF with a
    # cover and no report - which looks like a broken product rather than
    # like a choice somebody made.
    if not requested:
        return list(allowed)
    wanted = {str(s).strip() for s in requested if str(s).strip()}
    if not wanted:
        return list(allowed)
    return [key for key in allowed if key in wanted]


