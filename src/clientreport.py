class Canvas:
    """A cursor down a page, which starts a new one when it runs out.

    Every draw call returns through here rather than touching `pdf.Page`
    directly, so page breaks happen in one place. A section that draws its own
    pages is a section that eventually writes over a footer.
    """

    def __init__(self, document, meta):
        self.doc = document
        self.meta = meta
        self.page = None
        self.y = 0.0
        self.numbered = []
        self.new_page()

    def new_page(self, first=False):
        self.page = self.doc.page()
        self.y = pdf.CONTENT_TOP
        if not first:
            self.numbered.append(self.page)
            self._running_head()
        return self.page

    def _running_head(self):
        self.page.text(LEFT, 806, self.meta["workspace_name"],
                       pdf.HELV_BOLD, 8.5, MUTED)
        self.page.text_right(RIGHT, 806, self.meta["title"], pdf.HELV, 8.5,
                             MUTED)
        self.page.line(LEFT, 800, RIGHT, 800, RULE, 0.6)

    def space(self, amount):
        self.y -= amount
        return self

    def need(self, amount):
        """Break before drawing something that will not fit.

        Called with the height of the *whole* block - a heading plus its first
        rows - so a heading is never orphaned at the bottom of a page.
        """
        if self.y - amount < pdf.CONTENT_BOTTOM:
            self.new_page()
        return self

    # -- primitives

    def heading(self, text, size=15.0):
        self.need(48)
        self.space(6)
        self.page.text(LEFT, self.y, text, pdf.HELV_BOLD, size, INK)
        self.y -= 8
        self.page.line(LEFT, self.y, RIGHT, self.y, BRAND, 1.4)
        self.y -= 16
        return self

    def subheading(self, text):
        self.need(30)
        self.space(4)
        self.page.text(LEFT, self.y, text, pdf.HELV_BOLD, 10.5, INK)
        self.y -= 14
        return self

    def paragraph(self, text, size=9.5, colour=INK, font=pdf.HELV,
                  leading=13.0, indent=0.0):
        for line in pdf.wrap(text, WIDTH - indent, font, size):
            self.need(leading + 2)
            self.page.text(LEFT + indent, self.y, line, font, size, colour)
            self.y -= leading
        return self

    def note(self, text):
        return self.paragraph(text, 8.5, MUTED, pdf.HELV_OBLIQUE, 11.0)

    def bullet(self, text, colour=INK):
        lines = pdf.wrap(text, WIDTH - 16, pdf.HELV, 9.5)
        for index, line in enumerate(lines):
            self.need(14)
            if index == 0:
                self.page.rect(LEFT + 2, self.y + 3, 3, 3, colour)
            self.page.text(LEFT + 16, self.y, line, pdf.HELV, 9.5, INK)
            self.y -= 13
        return self

    def metrics(self, pairs, per_row=4):
        """A row of headline figures. The one shape a reader scans first."""
        pairs = [p for p in pairs if p is not None]
        for start in range(0, len(pairs), per_row):
            chunk = pairs[start:start + per_row]
            self.need(58)
            box = WIDTH / per_row
            for index, (label, value, hint) in enumerate(chunk):
                x = LEFT + index * box
                self.page.rect(x, self.y - 40, box - 8, 48, BAND)
                self.page.rect(x, self.y - 40, 2.5, 48, BRAND)
                self.page.text(x + 10, self.y - 2,
                               pdf.truncate(str(value), box - 26,
                                            pdf.HELV_BOLD, 17),
                               pdf.HELV_BOLD, 17, BRAND_DEEP)
                self.page.text(x + 10, self.y - 18,
                               pdf.truncate(label, box - 26, pdf.HELV, 8),
                               pdf.HELV, 8, MUTED)
                if hint:
                    self.page.text(x + 10, self.y - 30,
                                   pdf.truncate(hint, box - 26, pdf.HELV, 7),
                                   pdf.HELV, 7, FAINT)
            self.y -= 56
        return self

    def table(self, headers, rows, widths=None, aligns=None, note=None):
        """A table that breaks across pages and repeats its header when it does.

        A continued table with no header is a grid of unlabelled numbers, and
        that is exactly the page somebody screenshots and misreads.
        """
        count = len(headers)
        widths = widths or [WIDTH / count] * count
        aligns = aligns or (["l"] + ["r"] * (count - 1))

        def draw_header():
            self.need(26)
            self.page.rect(LEFT, self.y - 6, WIDTH, 18, BAND)
            x = LEFT
            for index, head in enumerate(headers):
                if aligns[index] == "r":
                    self.page.text_right(x + widths[index] - 6, self.y,
                                         head, pdf.HELV_BOLD, 8.5, MUTED)
                else:
                    self.page.text(x + 6, self.y,
                                   pdf.truncate(head, widths[index] - 12,
                                                pdf.HELV_BOLD, 8.5),
                                   pdf.HELV_BOLD, 8.5, MUTED)
                x += widths[index]
            self.y -= 20

        draw_header()
        if not rows:
            self.need(20)
            self.page.text(LEFT + 6, self.y, "No rows for this period.",
                           pdf.HELV_OBLIQUE, 9, MUTED)
            self.y -= 16
            return self

        for row in rows:
            if self.y - 16 < pdf.CONTENT_BOTTOM:
                self.new_page()
                draw_header()
            x = LEFT
            for index, cell in enumerate(row):
                value = "" if cell is None else str(cell)
                if aligns[index] == "r":
                    self.page.text_right(x + widths[index] - 6, self.y, value,
                                         pdf.HELV, 9, INK)
                else:
                    self.page.text(x + 6, self.y,
                                   pdf.truncate(value, widths[index] - 12,
                                                pdf.HELV, 9),
                                   pdf.HELV, 9, INK)
                x += widths[index]
            self.y -= 6
            self.page.line(LEFT, self.y, RIGHT, self.y, RULE, 0.4)
            self.y -= 10
        if note:
            self.space(2)
            self.note(note)
        return self

    def bars(self, rows, unit=""):
        """A horizontal bar chart. Vector, so it stays sharp at any zoom.

        Every bar prints its own value. A chart whose bars can only be read
        against an axis is a chart somebody reads wrong.
        """
        rows = [(str(label), value) for label, value in rows
                if isinstance(value, (int, float))]
        if not rows:
            return self.note("Nothing to chart for this period.")
        top = max((v for _, v in rows), default=0) or 1
        label_w = 150.0
        value_w = 60.0
        track = WIDTH - label_w - value_w
        for label, value in rows:
            self.need(18)
            self.page.text(LEFT, self.y, pdf.truncate(label, label_w - 8),
                           pdf.HELV, 9, INK)
            self.page.rect(LEFT + label_w, self.y - 2, track, 9, BAND)
            filled = max(1.0, track * (float(value) / float(top)))
            self.page.rect(LEFT + label_w, self.y - 2, filled, 9, BRAND)
            self.page.text_right(RIGHT, self.y, f"{value:,}{unit}",
                                 pdf.HELV_BOLD, 9, INK)
            self.y -= 17
        return self

    def unavailable(self, why):
        self.need(26)
        self.page.rect(LEFT, self.y - 8, 2.5, 20, WARN)
        self.page.text(LEFT + 10, self.y, "Not tracked", pdf.HELV_BOLD, 9,
                       WARN)
        self.y -= 13
        self.paragraph(why, 8.5, MUTED, pdf.HELV_OBLIQUE, 11.0, indent=10)
        return self


# --------------------------------------------------------------- formatting

def _n(value):
    """A count. `None` is "not tracked" and never renders as a number."""
    if value is None:
        return "n/a"
    try:
        return f"{int(value):,}"
    except (TypeError, ValueError):
        return str(value)


def _rate(numerator, denominator):
    """A percentage that always travels with the fraction it came from.

    "12%" is a claim. "12% (6/50)" is a claim somebody can check, and a
    denominator of fifty is the part a reader needs in order to not build a
    strategy on it.
    """
    if not denominator:
        return "n/a"
    if numerator is None:
        return "n/a"
    return f"{(100.0 * numerator / denominator):.1f}% ({numerator:,}/{denominator:,})"


def _period_label(start, end):
    if start and end:
        return f"{start} to {end}"
    if start:
        return f"From {start}"
    if end:
        return f"Up to {end}"
    return "All time"


