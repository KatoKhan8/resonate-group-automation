#!/usr/bin/env python3
"""Client reports: the document a workspace's results leave the building in.

Three templates, and the difference between them is who may read them rather
than how much detail they carry:

  EXECUTIVE     what a client's leadership needs. Outcomes, no machinery.
  DETAILED      the same, plus every audience breakdown the data supports.
  INTERNAL      operations. Provider usage, verification waterfall, MX,
                holds, jobs. Never leaves Resonate.

The rules the whole module is built to:

**Every number comes from `src/report.py`.** Nothing here counts anything
itself. A report that recomputes a funnel is a second definition of the
funnel, and the second one is the one that goes stale - so the same
`report.for_client` and `report.funnel_for` that the web dashboards read are
what fills these pages. "The report says something different from the screen"
is not a bug this product will have.

**A number nobody can know is named, never zeroed.** `report.unavailable()`
lists them, and a section whose data is unavailable prints the reason. A
client report showing "Meetings: 0" when nothing observes a calendar is a lie
that takes one meeting to discover.

**INTERNAL never renders from a client-facing request.** The template is
chosen server-side against a permission, not from a form field the browser
sends - see `src/web/api.py`.

**Observations are deterministic.** The Observations section is generated by
comparing counted values against stated thresholds, in `observations()`. No
model writes a strategic conclusion into a document a client will read.
"""
