def build(data, meta, sections=None):
    """The whole document, as PDF bytes.

    `data` is whatever `src/web/api.py` assembled from `src/report.py`. This
    function counts nothing; it lays out what it is given, and a key it does
    not find renders as "not tracked" rather than as zero.
    """
    template = meta.get("template") or EXECUTIVE
    if template not in TEMPLATES:
        raise ValueError(f"unknown report template: {template!r}")
    chosen = resolve_sections(template, sections)

    meta = dict(meta)
    meta.setdefault("template_label", TEMPLATE_LABEL[template])
    meta.setdefault("title", TEMPLATE_LABEL[template])
    meta.setdefault("generated_at", store.now()[:10])
    meta.setdefault("generated_by", "unknown")
    meta.setdefault("report_id", "-")
    meta.setdefault("campaign_label", "All campaigns")
    meta.setdefault("workspace_slug", "-")
    meta.setdefault("period", "All time")

    document = pdf.Document(
        title=f"{meta['workspace_name']} - {meta['template_label']}",
        subject=f"Reporting period: {meta['period']}")
    canvas = Canvas(document, meta)
    _cover(canvas, meta)

    for key in chosen:
        canvas.new_page()
        # Every renderer takes `meta`; the ones that ignore it accept it as a
        # keyword default. Branching on the section key here was how the
        # appendix ended up unable to see which template it was rendering
        # for, and printed a supplier's name into a client's document.
        RENDERERS[key](canvas, data, meta)

    _footers(document, meta)
    return document.render()


def _footers(document, meta):
    """Page numbers last, because the count is not known until the end."""
    pages = document.pages
    total = len(pages)
    for index, page in enumerate(pages, start=1):
        if index == 1:
            continue                     # the cover carries its own footer
        page.line(LEFT, 58, RIGHT, 58, RULE, 0.6)
        page.text(LEFT, 44, f"Resonate Group - {meta['workspace_name']}",
                  pdf.HELV, 7.5, FAINT)
        page.text_right(RIGHT, 44, f"Page {index} of {total}", pdf.HELV, 7.5,
                        FAINT)


def filename(meta):
    """A filename somebody can find again in a folder of thirty of them."""
    slug = "".join(ch if ch.isalnum() else "-"
                   for ch in str(meta.get("workspace_slug") or "workspace"))
    period = str(meta.get("period") or "all-time").replace(" ", "-")
    period = "".join(ch for ch in period if ch.isalnum() or ch == "-")
    return f"resonate-{slug}-{meta.get('template', EXECUTIVE)}-{period}.pdf"


