def _plural(count, one, many):
    """"1 company", not "1 companies"."""
    count = count or 0
    return f"{count:,} {one if count == 1 else many}"


def _humanise(key):
    """An internal key as a person reads it: `economic_buyer` -> Economic buyer.

    A client's document is not the place a reader meets this system's
    identifiers. Anything already written for people is left alone.
    """
    text = str(key)
    if "_" not in text:
        return text
    return text.replace("_", " ").strip().capitalize()


def _as_count(value):
    if isinstance(value, dict):
        for key in ("contacts", "count", "total", "n"):
            if isinstance(value.get(key), int):
                return value[key]
        return 0
    return value if isinstance(value, int) else 0


